import { readFile, writeFile, mkdir } from 'node:fs/promises';
const check = process.argv.includes('--check');
const destination = new URL('../supabase/functions/_shared/', import.meta.url);
await mkdir(destination, { recursive: true });
for (const name of ['engine', 'catalog', 'online-service', 'room-http']) {
  const source = (await readFile(new URL(`../src/${name}.ts`, import.meta.url), 'utf8')).replace(/\r\n/g, '\n').trimEnd() + '\n';
  const generated = '// Generated by scripts/sync-edge.mjs. Edit src/ instead.\n' + source.replace(/from '(\.\/[^']+)'/g, (_, path) => `from '${path}.ts'`);
  const target = new URL(`${name}.ts`, destination);
  if (check) {
    if ((await readFile(target, 'utf8').catch(() => '')).replace(/\r\n/g, '\n') !== generated) throw new Error(`Edge ${name}.ts is stale. Run npm run edge:sync.`);
  } else await writeFile(target, generated);
}
console.log(check ? 'Edge rules match the tested source.' : 'Edge shared source updated.');

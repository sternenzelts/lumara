import { build } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const output = new URL('../supabase/deploy/last-light.js', import.meta.url);
const result = await build({
  entryPoints: [fileURLToPath(new URL('../supabase/functions/last-light/index.ts', import.meta.url))],
  bundle: true, write: false, format: 'esm', platform: 'neutral', target: 'es2022', external: ['npm:*'],
  banner: { js: '// Generated by npm run edge:bundle. Paste this entire file into the Supabase last-light function.' },
});
const content = result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8').catch(() => '')).replace(/\r\n/g, '\n') !== content) throw new Error('Deployment bundle is stale. Run npm run edge:bundle.');
} else {
  await mkdir(new URL('.', output), { recursive: true }); await writeFile(output, content);
}
console.log('Single-file Supabase function verified.');
